;
; ===========================================================================
; FRF Mame106RGB V3L FIX4 INTERLEAVED6 EHB
; ===========================================================================
;
; One 32-pixel block is converted and written to all five native planes before
; the routine advances to the next block.
;
; This replaces the old arrangement:
;   complete planes 0-3 for the frame
;   restart the frame
;   complete plane 4
;
; Direct-screen output can display the bitmap while the CPU is writing it.
; Keeping all five writes within the same 32-pixel block greatly reduces the
; time in which colours 16-31 can combine new lower bits with an old bit 4.
;
; Interface is intentionally identical to the former _c2p6plane routine:
;
;   a0     chunky source
;   a1     struct BitMap *
;   d0.w   width in pixels, multiple of 32
;   d1.w   height in pixels
;   d2.w   destination X offset, multiple of 8
;   d3.w   destination Y offset
;   d4.l   chunky source bytes per row
;
; Source pixels must be native palette indices 0..31.
; ===========================================================================

        XDEF    _c2p6plane

        incdir  include:
        include graphics/gfx.i

        section code,code

_c2p6plane:
        movem.l d2-d7/a2-a6,-(sp)

        move.w  d1,c2p6i_rows
        beq     .exit

        move.w  d0,d5
        andi.w  #$001f,d5
        bne     .exit

        move.w  d2,d5
        andi.w  #$0007,d5
        bne     .exit

        cmpi.b  #6,bm_Depth(a1)
        blo     .exit

        ; Source row modulo.
        moveq   #0,d5
        move.w  d0,d5
        sub.l   d5,d4
        move.l  d4,c2p6i_srcmod

        ; Destination offset and row modulo.
        moveq   #0,d4
        move.w  bm_BytesPerRow(a1),d4

        ext.l   d2
        mulu.w  d4,d3
        lsr.l   #3,d2
        add.l   d2,d3

        moveq   #0,d5
        move.w  d0,d5
        lsr.w   #3,d5
        sub.l   d5,d4
        move.l  d4,c2p6i_dstmod

        lsr.w   #5,d0
        move.w  d0,c2p6i_blocks

        move.l  bm_Planes+0*4(a1),a2
        move.l  bm_Planes+1*4(a1),a3
        move.l  bm_Planes+2*4(a1),a4
        move.l  bm_Planes+3*4(a1),a5
        move.l  bm_Planes+4*4(a1),a6
        move.l  bm_Planes+5*4(a1),d5
        move.l  d5,c2p6i_plane5ptr

        add.l   d3,a2
        add.l   d3,a3
        add.l   d3,a4
        add.l   d3,a5
        add.l   d3,a6
        move.l  c2p6i_plane5ptr(pc),d5
        add.l   d3,d5
        move.l  d5,c2p6i_plane5ptr

        lea     c2p6i_pairtab0(pc),a1

.row:
        move.w  c2p6i_blocks(pc),c2p6i_blockleft

.block:
        lea     c2p6i_pairtab0(pc),a1

        ; ---------------------------------------------------------------
        ; Build plane 4 for the same 32 source pixels.
        ; Four lookup bytes become one plane longword.
        ; ---------------------------------------------------------------
        moveq   #0,d2
        moveq   #0,d7

        move.w  0(a0),d2
        andi.w  #$1f1f,d2
        move.b  0(a1,d2.l),d7
        move.w  2(a0),d2
        andi.w  #$1f1f,d2
        or.b    8192(a1,d2.l),d7
        move.w  4(a0),d2
        andi.w  #$1f1f,d2
        or.b    16384(a1,d2.l),d7
        move.w  6(a0),d2
        andi.w  #$1f1f,d2
        or.b    24576(a1,d2.l),d7
        rol.l   #8,d7

        move.w  8(a0),d2
        andi.w  #$1f1f,d2
        move.b  0(a1,d2.l),d7
        move.w  10(a0),d2
        andi.w  #$1f1f,d2
        or.b    8192(a1,d2.l),d7
        move.w  12(a0),d2
        andi.w  #$1f1f,d2
        or.b    16384(a1,d2.l),d7
        move.w  14(a0),d2
        andi.w  #$1f1f,d2
        or.b    24576(a1,d2.l),d7
        rol.l   #8,d7

        move.w  16(a0),d2
        andi.w  #$1f1f,d2
        move.b  0(a1,d2.l),d7
        move.w  18(a0),d2
        andi.w  #$1f1f,d2
        or.b    8192(a1,d2.l),d7
        move.w  20(a0),d2
        andi.w  #$1f1f,d2
        or.b    16384(a1,d2.l),d7
        move.w  22(a0),d2
        andi.w  #$1f1f,d2
        or.b    24576(a1,d2.l),d7
        rol.l   #8,d7

        move.w  24(a0),d2
        andi.w  #$1f1f,d2
        move.b  0(a1,d2.l),d7
        move.w  26(a0),d2
        andi.w  #$1f1f,d2
        or.b    8192(a1,d2.l),d7
        move.w  28(a0),d2
        andi.w  #$1f1f,d2
        or.b    16384(a1,d2.l),d7
        move.w  30(a0),d2
        andi.w  #$1f1f,d2
        or.b    24576(a1,d2.l),d7

        move.l  d7,-(sp)

        ; ---------------------------------------------------------------
        ; Build EHB selector plane 5 for the same 32 source pixels.
        ; Bit 5 chooses pens 32..63, the half-bright partners.
        ; ---------------------------------------------------------------
        lea     c2p6i_pairtab5(pc),a1
        moveq   #0,d2
        moveq   #0,d7

        move.w  0(a0),d2
        andi.w  #$2020,d2
        lsr.w   #5,d2
        move.b 0(a1,d2.l),d7
        move.w  2(a0),d2
        andi.w  #$2020,d2
        lsr.w   #5,d2
        or.b   512(a1,d2.l),d7
        move.w  4(a0),d2
        andi.w  #$2020,d2
        lsr.w   #5,d2
        or.b   1024(a1,d2.l),d7
        move.w  6(a0),d2
        andi.w  #$2020,d2
        lsr.w   #5,d2
        or.b   1536(a1,d2.l),d7
        rol.l   #8,d7

        move.w  8(a0),d2
        andi.w  #$2020,d2
        lsr.w   #5,d2
        move.b 0(a1,d2.l),d7
        move.w  10(a0),d2
        andi.w  #$2020,d2
        lsr.w   #5,d2
        or.b   512(a1,d2.l),d7
        move.w  12(a0),d2
        andi.w  #$2020,d2
        lsr.w   #5,d2
        or.b   1024(a1,d2.l),d7
        move.w  14(a0),d2
        andi.w  #$2020,d2
        lsr.w   #5,d2
        or.b   1536(a1,d2.l),d7
        rol.l   #8,d7

        move.w  16(a0),d2
        andi.w  #$2020,d2
        lsr.w   #5,d2
        move.b 0(a1,d2.l),d7
        move.w  18(a0),d2
        andi.w  #$2020,d2
        lsr.w   #5,d2
        or.b   512(a1,d2.l),d7
        move.w  20(a0),d2
        andi.w  #$2020,d2
        lsr.w   #5,d2
        or.b   1024(a1,d2.l),d7
        move.w  22(a0),d2
        andi.w  #$2020,d2
        lsr.w   #5,d2
        or.b   1536(a1,d2.l),d7
        rol.l   #8,d7

        move.w  24(a0),d2
        andi.w  #$2020,d2
        lsr.w   #5,d2
        move.b 0(a1,d2.l),d7
        move.w  26(a0),d2
        andi.w  #$2020,d2
        lsr.w   #5,d2
        or.b   512(a1,d2.l),d7
        move.w  28(a0),d2
        andi.w  #$2020,d2
        lsr.w   #5,d2
        or.b   1024(a1,d2.l),d7
        move.w  30(a0),d2
        andi.w  #$2020,d2
        lsr.w   #5,d2
        or.b   1536(a1,d2.l),d7

        move.l  d7,-(sp)
        ; ---------------------------------------------------------------
        ; Existing proven lower-four-plane transpose, one 32-pixel block.
        ; Outputs at the end:
        ;   d7 plane 0
        ;   d2 plane 1
        ;   d5 plane 2
        ;   d0 plane 3
        ; ---------------------------------------------------------------
        move.l  (a0)+,d0
        move.l  (a0)+,d2
        move.l  (a0)+,d1
        move.l  (a0)+,d3

        move.l  #$0f0f0f0f,d6
        and.l   d6,d0
        and.l   d6,d1
        and.l   d6,d2
        and.l   d6,d3
        lsl.l   #4,d0
        lsl.l   #4,d1
        or.l    d2,d0
        or.l    d3,d1

        move.l  (a0)+,d2
        move.l  (a0)+,d6
        move.l  (a0)+,d3
        move.l  (a0)+,d7

        move.l  #$0f0f0f0f,d4
        and.l   d4,d2
        and.l   d4,d6
        and.l   d4,d3
        and.l   d4,d7
        lsl.l   #4,d2
        lsl.l   #4,d3
        or.l    d6,d2
        or.l    d7,d3

        move.w  d2,d6
        move.w  d3,d7
        move.w  d0,d2
        move.w  d1,d3
        swap    d2
        swap    d3
        move.w  d2,d0
        move.w  d3,d1
        move.w  d6,d2
        move.w  d7,d3

        move.l  #$33333333,d4
        move.l  d2,d6
        move.l  d3,d7
        lsr.l   #2,d6
        lsr.l   #2,d7
        eor.l   d0,d6
        eor.l   d1,d7
        and.l   d4,d6
        and.l   d4,d7
        eor.l   d6,d0
        eor.l   d7,d1
        lsl.l   #2,d6
        lsl.l   #2,d7
        eor.l   d6,d2
        eor.l   d7,d3

        move.l  #$00ff00ff,d4
        move.l  d1,d6
        move.l  d3,d7
        lsr.l   #8,d6
        lsr.l   #8,d7
        eor.l   d0,d6
        eor.l   d2,d7
        and.l   d4,d6
        and.l   d4,d7
        eor.l   d6,d0
        eor.l   d7,d2
        lsl.l   #8,d6
        lsl.l   #8,d7
        eor.l   d6,d1
        eor.l   d7,d3

        move.l  #$55555555,d4
        move.l  d1,d5
        move.l  d3,d7
        lsr.l   #1,d5
        lsr.l   #1,d7
        eor.l   d0,d5
        eor.l   d2,d7
        and.l   d4,d5
        and.l   d4,d7
        eor.l   d5,d0
        eor.l   d7,d2
        add.l   d5,d5
        add.l   d7,d7
        eor.l   d1,d5
        eor.l   d3,d7

        ; All five writes for this block are adjacent.
        move.l  d7,(a2)+
        move.l  d2,(a3)+
        move.l  d5,(a4)+
        move.l  d0,(a5)+
        ; Pop plane 5 and plane 4, then write both beside planes 0..3.
        move.l  (sp)+,d1
        move.l  (sp)+,d6
        move.l  d6,(a6)+
        move.l  c2p6i_plane5ptr(pc),a1
        move.l  d1,(a1)+
        move.l  a1,c2p6i_plane5ptr

        subq.w  #1,c2p6i_blockleft
        bne     .block

        move.l  c2p6i_srcmod(pc),d0
        add.l   d0,a0

        move.l  c2p6i_dstmod(pc),d0
        add.l   d0,a2
        add.l   d0,a3
        add.l   d0,a4
        add.l   d0,a5
        add.l   d0,a6
        move.l  c2p6i_plane5ptr(pc),a1
        add.l   d0,a1
        move.l  a1,c2p6i_plane5ptr

        subq.w  #1,c2p6i_rows
        bne     .row

.exit:
        movem.l (sp)+,d2-d7/a2-a6
        rts

        even

c2p6i_rows:
        dc.w    0
c2p6i_blocks:
        dc.w    0
c2p6i_blockleft:
        dc.w    0
        even
c2p6i_srcmod:
        dc.l    0
c2p6i_dstmod:
        dc.l    0

